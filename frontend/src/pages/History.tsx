import React, { useEffect, useState } from "react";
import { Link } from "react-router-dom";
import {
  Clock,
  Download,
  Filter,
  HeartPulse,
  History as HistoryIcon,
  Mail,
  MessageSquare,
  RefreshCw,
  Search,
  Trash2,
} from "lucide-react";
import { api } from "../services/api";
import type { PredictionHistoryItem } from "../types";

export const History: React.FC = () => {
  const [history, setHistory] = useState<PredictionHistoryItem[]>([]);
  const [loading, setLoading] = useState(true);
  const [searchTerm, setSearchTerm] = useState("");
  const [riskFilter, setRiskFilter] = useState<string>("all");
  const [deletingId, setDeletingId] = useState<string | null>(null);

  const fetchHistory = async () => {
    setLoading(true);
    try {
      const data = await api.getHistory();
      setHistory(data);
    } catch (err) {
      console.error("Failed to load history:", err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchHistory();
  }, []);

  const handleDelete = async (id: string) => {
    if (!window.confirm("Are you sure you want to delete this assessment record?")) return;
    setDeletingId(id);
    try {
      await api.deleteHistoryItem(id);
      setHistory((prev) => prev.filter((item) => item.id !== id));
    } catch (err) {
      console.error("Delete failed:", err);
    } finally {
      setDeletingId(null);
    }
  };

  const handleExportJson = () => {
    const dataStr = "data:text/json;charset=utf-8," + encodeURIComponent(JSON.stringify(history, null, 2));
    const downloadAnchor = document.createElement("a");
    downloadAnchor.setAttribute("href", dataStr);
    downloadAnchor.setAttribute("download", `diabetes_prediction_history_${new Date().toISOString().slice(0, 10)}.json`);
    document.body.appendChild(downloadAnchor);
    downloadAnchor.click();
    downloadAnchor.remove();
  };

  const getInitials = (name: string) => {
    if (!name || name === "Anonymous Patient") return "PT";
    const parts = name.trim().split(" ");
    if (parts.length >= 2) return `${parts[0][0]}${parts[1][0]}`.toUpperCase();
    return name.slice(0, 2).toUpperCase();
  };

  const handleNotifyPatient = (item: PredictionHistoryItem) => {
    const name = item.patient_name || item.patient_data.patient_name || "Patient";
    const email = item.patient_email || item.patient_data.patient_email || "";
    const subject = encodeURIComponent(`DiaPredict AI: Clinical Assessment Summary for ${name}`);
    const body = encodeURIComponent(
      `Dear ${name},\n\nYour clinical diabetes risk stratification record is summarized below:\n\n` +
      `Diagnostic Outcome: ${item.label}\n` +
      `Calculated Risk Probability: ${(item.probability * 100).toFixed(1)}% (${item.risk_level} Risk)\n` +
      `Assessment Timestamp: ${new Date(item.timestamp).toLocaleString()}\n\n` +
      `Recorded Physiological Vitals:\n` +
      `- Plasma Glucose: ${item.patient_data.Glucose} mg/dL\n` +
      `- Body Mass Index: ${item.patient_data.BMI} kg/m²\n` +
      `- Age: ${item.patient_data.Age} years\n` +
      `- Blood Pressure: ${item.patient_data.BloodPressure} mmHg\n\n` +
      `Recommendation:\n` +
      `${item.prediction === 1 ? "Elevated risk detected. Clinical follow-up HbA1c test strongly recommended." : "Vitals are within non-diabetic range. Continue annual routine screenings."}\n\n` +
      `*Generated by DiaPredict AI Clinical Decision Support.`
    );
    window.open(`mailto:${email}?subject=${subject}&body=${body}`, "_blank");
  };

  const handleShareWhatsApp = (item: PredictionHistoryItem) => {
    const name = item.patient_name || item.patient_data.patient_name || "Patient";
    const text = encodeURIComponent(
      `*DiaPredict AI Clinical Summary*\n` +
      `Patient: ${name}\n` +
      `Outcome: ${item.label} (${(item.probability * 100).toFixed(1)}% - ${item.risk_level} Risk)\n` +
      `Glucose: ${item.patient_data.Glucose} mg/dL | BMI: ${item.patient_data.BMI} | Age: ${item.patient_data.Age}y\n` +
      `Status: ${item.prediction === 1 ? "Elevated Metabolic Risk" : "Normal Non-Diabetic Distribution"}`
    );
    window.open(`https://api.whatsapp.com/send?text=${text}`, "_blank");
  };

  const filteredHistory = history.filter((item) => {
    const matchesRisk =
      riskFilter === "all" ||
      (riskFilter === "diabetic" && item.prediction === 1) ||
      (riskFilter === "healthy" && item.prediction === 0) ||
      item.risk_level.toLowerCase() === riskFilter.toLowerCase();

    const pName = item.patient_name || item.patient_data.patient_name || "";
    const pEmail = item.patient_email || item.patient_data.patient_email || "";

    const matchesSearch =
      searchTerm === "" ||
      pName.toLowerCase().includes(searchTerm.toLowerCase()) ||
      pEmail.toLowerCase().includes(searchTerm.toLowerCase()) ||
      item.label.toLowerCase().includes(searchTerm.toLowerCase()) ||
      item.patient_data.Glucose.toString().includes(searchTerm) ||
      item.patient_data.BMI.toString().includes(searchTerm) ||
      item.patient_data.Age.toString().includes(searchTerm);

    return matchesRisk && matchesSearch;
  });

  return (
    <div className="space-y-8 max-w-5xl mx-auto">
      {/* ─────────────────────────────────────────────────────────────
          HEADER
         ───────────────────────────────────────────────────────────── */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
        <div>
          <div className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full bg-white/5 border border-white/10 text-xs font-medium text-amber-300 mb-2">
            <HistoryIcon className="w-3.5 h-3.5" /> Clinical Audit Trail
          </div>
          <h1 className="font-serif text-3xl sm:text-4xl text-white font-normal">
            Assessment <span className="italic text-amber-300">History Log</span>
          </h1>
          <p className="text-xs sm:text-sm text-[#9fa89f]">
            Chronological audit of all past clinical inferences generated during demonstration testing
          </p>
        </div>

        <div className="flex items-center gap-2">
          {history.length > 0 && (
            <button
              onClick={handleExportJson}
              className="px-4 py-2 rounded-full bg-white/5 hover:bg-white/10 text-xs text-[#b8c0b6] border border-white/10 flex items-center gap-1.5 transition-all"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Export Audit Trail</span>
            </button>
          )}

          <button
            onClick={fetchHistory}
            className="p-2 rounded-full bg-white/5 hover:bg-white/10 text-slate-300 border border-white/10 transition-all"
            title="Refresh history"
          >
            <RefreshCw className={`w-4 h-4 ${loading ? "animate-spin" : ""}`} />
          </button>
        </div>
      </div>

      {/* ─────────────────────────────────────────────────────────────
          SEARCH & FILTER BAR
         ───────────────────────────────────────────────────────────── */}
      <div className="glass-panel-deep p-4 flex flex-col sm:flex-row items-center justify-between gap-3">
        <div className="relative w-full sm:w-80">
          <Search className="w-3.5 h-3.5 text-slate-400 absolute left-3.5 top-1/2 -translate-y-1/2" />
          <input
            type="text"
            placeholder="Search by patient name, email, glucose, BMI..."
            value={searchTerm}
            onChange={(e) => setSearchTerm(e.target.value)}
            className="w-full input-minimal pl-9 pr-3.5 py-2 text-xs"
          />
        </div>

        <div className="flex flex-wrap items-center gap-2 w-full sm:w-auto pt-1 sm:pt-0">
          <span className="text-[11px] text-[#849386] flex items-center gap-1 mr-1">
            <Filter className="w-3 h-3" /> Filter:
          </span>
          {[
            { id: "all", label: "All Records" },
            { id: "diabetic", label: "Diabetic" },
            { id: "healthy", label: "Healthy" },
            { id: "high", label: "High Risk" },
          ].map((pill) => (
            <button
              key={pill.id}
              onClick={() => setRiskFilter(pill.id)}
              className={`px-3 py-1.5 rounded-full text-xs font-medium whitespace-nowrap transition-all ${
                riskFilter === pill.id
                  ? "bg-amber-500/20 text-amber-300 border border-amber-500/40"
                  : "bg-white/5 text-[#849386] hover:text-white border border-transparent"
              }`}
            >
              {pill.label}
            </button>
          ))}
        </div>
      </div>

      {/* ─────────────────────────────────────────────────────────────
          HISTORY ITEMS (REF 2 TABLE CAPSULES)
         ───────────────────────────────────────────────────────────── */}
      {loading ? (
        <div className="text-center py-24 space-y-3">
          <RefreshCw className="w-6 h-6 text-amber-400 animate-spin mx-auto" />
          <p className="text-xs text-[#849386] font-mono">Loading patient logs...</p>
        </div>
      ) : filteredHistory.length === 0 ? (
        <div className="glass-panel-deep p-12 text-center space-y-4">
          <div className="w-12 h-12 rounded-full bg-white/5 border border-white/10 flex items-center justify-center mx-auto text-slate-400">
            <HistoryIcon className="w-6 h-6 text-[#849386]" />
          </div>
          <div className="space-y-1">
            <h3 className="text-base font-semibold text-white">No Inferences Logged Yet</h3>
            <p className="text-xs text-[#849386] max-w-sm mx-auto">
              {searchTerm || riskFilter !== "all"
                ? "No clinical records match your current filter query."
                : "No patient risk assessments have been conducted in this session yet."}
            </p>
          </div>
          <Link
            to="/assessment"
            className="btn-pill-dark inline-flex"
          >
            <div className="icon-badge">
              <HeartPulse className="w-3.5 h-3.5 text-amber-300" />
            </div>
            <span>RUN FIRST PATIENT ASSESSMENT</span>
          </Link>
        </div>
      ) : (
        <div className="space-y-3">
          {filteredHistory.map((item) => {
            const patientName = item.patient_name || item.patient_data.patient_name || "Anonymous Patient";
            const patientEmail = item.patient_email || item.patient_data.patient_email;

            return (
              <div
                key={item.id}
                className="glass-card-dark p-4 sm:p-5 flex flex-col lg:flex-row lg:items-center justify-between gap-4 hover:border-amber-500/30 transition-all"
              >
                {/* 1. Patient Identity & Outcome Section */}
                <div className="flex items-start sm:items-center gap-3.5 min-w-[260px]">
                  {/* Patient Initials Avatar */}
                  <div
                    className={`w-11 h-11 rounded-2xl border flex items-center justify-center shrink-0 font-bold font-mono text-xs shadow-md ${
                      item.prediction === 1
                        ? "bg-amber-950/30 text-amber-300 border-amber-500/30"
                        : "bg-emerald-950/30 text-emerald-400 border-emerald-500/30"
                    }`}
                  >
                    {getInitials(patientName)}
                  </div>

                  <div className="space-y-1">
                    <div className="flex flex-wrap items-center gap-2">
                      <span className="text-sm font-bold text-white tracking-tight">
                        {patientName}
                      </span>
                      <span
                        className={`text-[10px] font-mono px-2 py-0.5 rounded-full border ${
                          item.prediction === 1
                            ? "bg-amber-500/10 text-amber-300 border-amber-500/30 font-semibold"
                            : "bg-emerald-500/10 text-emerald-400 border-emerald-500/30 font-medium"
                        }`}
                      >
                        {item.label} • {(item.probability * 100).toFixed(1)}%
                      </span>
                    </div>

                    <div className="flex flex-wrap items-center gap-3 text-xs text-[#849386]">
                      {patientEmail ? (
                        <span className="flex items-center gap-1 font-mono text-[11px] text-[#b8c0b6]">
                          <Mail className="w-3 h-3 text-amber-400/80" />
                          {patientEmail}
                        </span>
                      ) : (
                        <span className="text-[11px] text-[#687368] font-mono">No email recorded</span>
                      )}
                      <span className="flex items-center gap-1 font-mono text-[10px]">
                        <Clock className="w-3 h-3 text-[#687368]" />
                        {new Date(item.timestamp).toLocaleDateString()} at{" "}
                        {new Date(item.timestamp).toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" })}
                      </span>
                    </div>
                  </div>
                </div>

                {/* 2. Key Physiological Parameters */}
                <div className="grid grid-cols-4 gap-3 sm:gap-6 text-xs text-slate-300 border-t lg:border-t-0 lg:border-l border-white/5 pt-3 lg:pt-0 lg:pl-6 shrink-0">
                  <div>
                    <span className="text-[10px] text-[#849386] block">Glucose</span>
                    <span className="font-mono font-bold text-white">{item.patient_data.Glucose} mg/dL</span>
                  </div>
                  <div>
                    <span className="text-[10px] text-[#849386] block">BMI</span>
                    <span className="font-mono font-bold text-white">{item.patient_data.BMI}</span>
                  </div>
                  <div>
                    <span className="text-[10px] text-[#849386] block">Age</span>
                    <span className="font-mono font-bold text-white">{item.patient_data.Age} yrs</span>
                  </div>
                  <div>
                    <span className="text-[10px] text-[#849386] block">Blood Press.</span>
                    <span className="font-mono font-bold text-white">{item.patient_data.BloodPressure}</span>
                  </div>
                </div>

                {/* 3. Interactive Actions: Dispatch & Delete */}
                <div className="flex items-center justify-end gap-2 pt-2 lg:pt-0 border-t lg:border-t-0 border-white/5 shrink-0">
                  {patientEmail && (
                    <button
                      type="button"
                      onClick={() => handleNotifyPatient(item)}
                      className="p-2 rounded-xl bg-white/5 hover:bg-white/10 text-slate-300 hover:text-amber-300 border border-white/10 transition-all"
                      title={`Send diagnostic report email to ${patientName}`}
                    >
                      <Mail className="w-4 h-4" />
                    </button>
                  )}

                  <button
                    type="button"
                    onClick={() => handleShareWhatsApp(item)}
                    className="p-2 rounded-xl bg-emerald-500/10 hover:bg-emerald-500/20 text-emerald-400 border border-emerald-500/20 transition-all"
                    title={`Share ${patientName}'s diagnostic summary via WhatsApp`}
                  >
                    <MessageSquare className="w-4 h-4" />
                  </button>

                  <button
                    type="button"
                    onClick={() => handleDelete(item.id)}
                    disabled={deletingId === item.id}
                    className="p-2 rounded-xl text-slate-500 hover:text-rose-400 hover:bg-rose-500/10 transition-colors"
                    title="Delete record from audit ledger"
                  >
                    <Trash2 className="w-4 h-4" />
                  </button>
                </div>
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
};
